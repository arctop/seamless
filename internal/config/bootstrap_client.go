// The configs a paired Client is written with (plan networked-relay;
// cmd/seamlessd setup_client.go). A Client that pairs holds no copy of the
// server's key: a key device holds a key of its own, minted by the server for
// this computer alone and revocable on its Devices page, and a relay client
// holds nothing at all, since the relay on this computer names every caller to
// the server by its uid. Both are written by the rules every bootstrap keeps
// (first-run-key-bootstrap-rules): a config file anywhere in the search order
// is never edited, the create is O_EXCL at 0600, and an identical file is the
// one existing file that is not an error.

// RelaySocketURL is the server_url of a Client whose relay serves this
// computer's agents: the socket path agents dial beside a peer_auth daemon
// (internal/relay's DefaultSocketPath), which the relay serves on a Client.
const RelaySocketURL = "unix:///opt/seamless/run/seamlessd.sock"

// ErrConfigExists is a Client's config that cannot be written because a
// config file is there already: setup checks it before it pairs, since a key
// the server minted and no file could take is a key lost.
var ErrConfigExists = errors.New("a config file is there already, and it is never edited on your behalf")

// ClientConfigTarget says where a Client's config would be written:
// existing is the config file the search finds today ("" when there is none),
// and path is the file a bootstrap creates when there is none.
func ClientConfigTarget() (existing, path string, err error) {
	existing, _, err = findConfigFile(true)
	if err != nil {
		return "", "", fmt.Errorf("config.ClientConfigTarget: %w", err)
	}
	home, err := os.UserHomeDir()
	if err != nil {
		return existing, "", fmt.Errorf("config.ClientConfigTarget: %w", err)
	}
	return existing, filepath.Join(home, ".config", "seamless", "seamless.yaml"), nil
}

// EnsureDeviceClientConfig writes the config of a Client paired as a key
// device: role: client, the server_url it dials, this computer's own device
// key (the pairing's answer, never the server's key), and, when caFile is
// set, the certificate this computer trusts the server by (tls.ca_file). It
// writes only where no config file is: any existing one, even one naming the
// same server, holds another key, and the refusal names the lines to add by
// hand. It returns the path written.
func EnsureDeviceClientConfig(serverURL, key, caFile string) (string, error) {
	const op = "config.EnsureDeviceClientConfig"
	url, err := clientServerURL(serverURL)
	if err != nil {
		return "", fmt.Errorf("%s: %w", op, err)
	}
	key = strings.TrimSpace(key)
	if key == "" || strings.ContainsAny(key, "\r\n") {
		return "", fmt.Errorf("%s: no device key", op)
	}
	if _, set := os.LookupEnv(envMCPAPIKey); set {
		// It would override the file's key at every later Load.
		return "", fmt.Errorf("%s: %s is set, and would stand in for this computer's own key at every load: unset it", op, envMCPAPIKey)
	}
	content := "# Generated by seamlessd setup when this computer paired with its server as a\n" +
		"# key device. Every key, its default, and its SEAMLESS_* env override: see\n" +
		"# seamless.yaml.example in the repo or /docs/reference/configuration/ on the\n" +
		"# docs site.\n" +
		"#\n" +
		"# role: client means this machine runs no daemon of its own: every surface\n" +
		"# dials server_url instead, so there is no data_dir here.\n" +
		"role: client\n" +
		"# Base URL of the seamlessd this machine dials.\n" +
		"# env: SEAMLESS_SERVER_URL\n" +
		"server_url: " + yamlString(url) + "\n"
	if caFile != "" {
		content += "tls:\n" +
			"  # The server's certificate, as this computer compared it at pairing.\n" +
			"  # env: SEAMLESS_TLS_CA_FILE\n" +
			"  ca_file: " + yamlString(caFile) + "\n"
	}
	content += "mcp:\n" +
		"  # This computer's own device key, from its pairing: the server lists it on\n" +
		"  # its Devices page, where revoking it locks this computer out alone.\n" +
		"  # env: SEAMLESS_MCP_API_KEY\n" +
		"  api_key: " + yamlString(key) + "\n"
	path, err := writeClientConfig(content, nil)
	if err != nil {
		return "", fmt.Errorf("%s: %w", op, err)
	}
	return path, nil
}

// EnsureSocketClientConfig writes the config of a Client whose relay serves
// its agents: role: client and the relay's socket (RelaySocketURL), with no
// key -- the relay names each caller to the server by its uid. A config file
// that already says exactly this is adopted (nothing is written, "" is
// returned), so a run again is not an error; any other is the refusal.
//
// SEAMLESS_SERVER_URL is not judged here: in setup it is the pairing's input,
// the server's https address, and the installers drop it before anything
// loads the config this writes.
func EnsureSocketClientConfig() (string, error) {
	const op = "config.EnsureSocketClientConfig"
	content := "# Generated by seamlessd setup for a computer whose relay serves its agents:\n" +
		"# the relay (seamlessd relay, its own system account) forwards every request\n" +
		"# to the server it paired with, and names each caller to it by its uid. Every\n" +
		"# key, its default, and its SEAMLESS_* env override: see seamless.yaml.example\n" +
		"# in the repo or /docs/reference/configuration/ on the docs site.\n" +
		"#\n" +
		"# No mcp.api_key: this computer holds no key of the server's.\n" +
		"role: client\n" +
		"# The relay's socket.\n" +
		"# env: SEAMLESS_SERVER_URL\n" +
		"server_url: " + yamlString(RelaySocketURL) + "\n"
	same := func(loaded Config) bool {
		return loaded.IsClient() && loaded.SocketPath() != "" && strings.TrimSuffix(loaded.AdvertisedURL, "/") == RelaySocketURL &&
			strings.TrimSpace(loaded.MCP.APIKey) == ""
	}
	path, err := writeClientConfig(content, same)
	if err != nil {
		return "", fmt.Errorf("%s: %w", op, err)
	}
	return path, nil
}

// writeClientConfig creates the Client config with content where the search
// finds none, O_EXCL at 0600, and returns its path. A config file the search
// finds, or one that won the create's race, is adopted when same says it is
// this one (and "" is returned), and refused otherwise; same nil adopts none.
func writeClientConfig(content string, same func(Config) bool) (string, error) {
	existing, path, err := ClientConfigTarget()
	if err != nil {
		return "", err
	}
	adopt := func(p string) (string, error) {
		if same != nil {
			if loaded, lerr := LoadFrom(p); lerr == nil && same(loaded) {
				return "", nil
			}
		}
		return "", fmt.Errorf("%s: %w", p, ErrConfigExists)
	}
	if existing != "" {
		return adopt(existing)
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
		return "", err
	}
	f, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o600)
	if err != nil {
		if errors.Is(err, fs.ErrExist) {
			return adopt(path)
		}
		return "", err
	}
	if _, err := f.WriteString(content); err != nil {
		_ = f.Close()
		return "", fmt.Errorf("write %s: %w", path, err)
	}
	if err := f.Sync(); err != nil {
		_ = f.Close()
		return "", fmt.Errorf("sync %s: %w", path, err)
	}
	if err := f.Close(); err != nil {
		return "", fmt.Errorf("close %s: %w", path, err)
	}
	if _, err := LoadFrom(path); err != nil {
		return "", fmt.Errorf("the config just written does not load: %w", err)
	}
	return path, nil
}
