// testdata/v0.8.2/seamless.rb is the cask goreleaser pushed to
// arctop/homebrew-tap for v0.8.2, and checksums.txt and its Sigstore bundle
// are that release's assets.
const v082 = "testdata/v0.8.2"

// The cask releasekit renders is goreleaser's, line for line, but for the
// header naming what generated it.
func TestRenderCask_IsGoreleasersCask(t *testing.T) {
	sums, err := os.ReadFile(filepath.Join(v082, "checksums.txt"))
	require.NoError(t, err)
	want, err := os.ReadFile(filepath.Join(v082, "seamless.rb"))
	require.NoError(t, err)

	got, err := renderCask(repoConfig(t), "v0.8.2", sums)
	require.NoError(t, err)
	gotHead, gotRest, _ := strings.Cut(got, "\n")
	wantHead, wantRest, _ := strings.Cut(string(want), "\n")
	require.Equal(t, "# This file was generated by GoReleaser. DO NOT EDIT.", wantHead)
	require.Equal(t, caskHeader, gotHead)
	require.Equal(t, wantRest, gotRest)
}

// No cask for a prerelease (goreleaser's skip_upload: auto), and none from a
// checksums.txt that lacks an archive or lists it twice.
func TestRenderCask_Refuses(t *testing.T) {
	sums, err := os.ReadFile(filepath.Join(v082, "checksums.txt"))
	require.NoError(t, err)
	_, err = renderCask(repoConfig(t), "v0.9.0-rc.1", sums)
	require.ErrorContains(t, err, "prerelease")

	var kept []string
	for l := range strings.SplitSeq(string(sums), "\n") {
		if !strings.Contains(l, "linux_arm64") {
			kept = append(kept, l)
		}
	}
	_, err = renderCask(repoConfig(t), "v0.8.2", []byte(strings.Join(kept, "\n")))
	require.ErrorContains(t, err, "linux_arm64")
}

// The cask command pins only a checksums.txt signed for exactly that tag by
// this repository's release workflow: the updater's check, offline.
func TestCaskCommand_ChecksTheReleaseSignature(t *testing.T) {
	args := func(tag string) []string {
		return []string{"cask", "-root", repoRoot, "-tag", tag,
			"-checksums", filepath.Join(v082, "checksums.txt"),
			"-bundle", filepath.Join(v082, "checksums.txt.sigstore.json")}
	}
	var out bytes.Buffer
	require.NoError(t, run(args("v0.8.2"), &out))
	require.Contains(t, out.String(), `version "0.8.2"`)

	err := run(args("v0.8.1"), &bytes.Buffer{})
	require.ErrorContains(t, err, "checksums.txt is not v0.8.1's")

	tampered := filepath.Join(t.TempDir(), "checksums.txt")
	sums, err := os.ReadFile(filepath.Join(v082, "checksums.txt"))
	require.NoError(t, err)
	require.NoError(t, os.WriteFile(tampered, bytes.Replace(sums, []byte("2e09"), []byte("2e0a"), 1), 0o644))
	a := args("v0.8.2")
	a[6] = tampered
	require.Error(t, run(a, &bytes.Buffer{}))
}

func TestRun_FlagErrors(t *testing.T) {
	require.ErrorContains(t, run(nil, &bytes.Buffer{}), "usage")
	require.ErrorContains(t, run([]string{"nope"}, &bytes.Buffer{}), "unknown command")
	require.ErrorContains(t, run([]string{"check-darwin", "-tag", "v0.9.0"}, &bytes.Buffer{}), "needs -tag-object -assets")
	require.ErrorContains(t, run([]string{"cask", "-tag", "v0.9.0", "-checksums", "a", "-bundle", "b", "extra"}, &bytes.Buffer{}), "takes no arguments")
	require.ErrorContains(t, run([]string{"manifest"}, &bytes.Buffer{}), "name the asset files")
}
