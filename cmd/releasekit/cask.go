package main

import (
	"fmt"
	"strings"

	"github.com/arctop/seamless/internal/update"
)

// The Homebrew cask (`brew install arctop/tap/seamless`), which goreleaser's
// homebrew_casks block wrote and pushed from CI until the macOS build moved
// to the owner's Mac. scripts/release/cask.sh renders it here after the
// release publishes, from the release's own Sigstore-checked checksums.txt,
// and pushes it to arctop/homebrew-tap with the owner's login, so CI holds
// no token for the tap. The text is goreleaser's, line for line, but for the
// first: testdata/v0.8.2 holds the cask goreleaser pushed for v0.8.2, and
// TestRenderCask_IsGoreleasersCask renders that release's checksums.txt back
// into it.

const (
	caskName     = "seamless"
	caskHomepage = "https://thereisnospoon.org"
	// The GitHub repository's description verbatim (the cross-surface
	// consistency rule).
	caskDesc    = "Local-first shared memory and task coordination for AI coding agents. One Go binary, MCP server, markdown files you own. Hooks for Claude Code and Codex CLI (and their desktop apps)."
	caskCaveats = `Connect your agent clients (hooks, MCP registration, skills):
  seamlessd install-hooks
Then start the daemon (it bootstraps config + key on first run):
  seamlessd serve
Quickstart: https://thereisnospoon.org/docs/quickstart/
`
	caskHeader = "# Generated by scripts/release/cask.sh from the release's checksums.txt. DO NOT EDIT."
)

// caskOS is one platform stanza: Homebrew's on_<os>, with goreleaser's
// on_arm before on_intel.
var caskOS = []struct{ stanza, goos string }{{"on_macos", "darwin"}, {"on_linux", "linux"}}

var caskArch = []struct{ stanza, goarch string }{{"on_arm", "arm64"}, {"on_intel", "amd64"}}

// renderCask writes the cask for tag from checksums, that release's
// checksums.txt. A prerelease gets none: like goreleaser's skip_upload: auto,
// brew must never move anyone onto a release candidate.
func renderCask(cfg grConfig, tag string, checksums []byte) (string, error) {
	v, ok := update.ParseTag(tag)
	if !ok {
		return "", fmt.Errorf("%s is not a published release's tag (vX.Y.Z); a prerelease gets no cask", tag)
	}
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }
	w("%s\n", caskHeader)
	w("cask %q do\n", caskName)
	w("  version %q\n\n", v.String())
	for _, o := range caskOS {
		w("  %s do\n", o.stanza)
		for _, a := range caskArch {
			name, err := cfg.archiveName(v.String(), o.goos, a.goarch)
			if err != nil {
				return "", err
			}
			sum, err := update.ChecksumOf(checksums, name)
			if err != nil {
				return "", err
			}
			urlName, err := cfg.archiveName("#{version}", o.goos, a.goarch)
			if err != nil {
				return "", err
			}
			w("    %s do\n", a.stanza)
			w("      sha256 %q\n", sum)
			w("      url \"%s/v#{version}/%s\"\n", update.ReleaseDownloadBase, urlName)
			w("    end\n")
		}
		w("  end\n")
	}
	w("\n")
	w("  name %q\n", caskName)
	w("  desc %q\n", caskDesc)
	w("  homepage %q\n\n", caskHomepage)
	w("  livecheck do\n    skip \"Auto-generated on release.\"\n  end\n\n")
	var staged []string
	for _, bd := range cfg.Builds {
		w("  binary %q\n", bd.Binary)
		staged = append(staged, fmt.Sprintf("%q", "{{staged_path}}/"+bd.Binary))
	}
	w("\n")
	// Homebrew quarantines every cask download on macOS; the strip stays as
	// a fallback for what notarization cannot cover: a bare Mach-O carries no
	// stapled ticket, so an offline first launch can still be refused.
	w("  postflight_steps do\n    on_macos do\n")
	w("      run \"/usr/bin/xattr\",\n")
	w("          args:         [\"-dr\", \"com.apple.quarantine\", %s],\n", strings.Join(staged, ", "))
	w("          must_succeed: false\n")
	w("    end\n  end\n\n")
	w("  zap :not_required\n\n")
	w("  caveats <<~EOS\n")
	for line := range strings.SplitSeq(strings.TrimSuffix(caskCaveats, "\n"), "\n") {
		w("    %s\n", line)
	}
	w("  EOS\n")
	w("end\n")
	return b.String(), nil
}
